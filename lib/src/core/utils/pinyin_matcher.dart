    final cleanTarget = target.trim();
    final cleanQuery = query.trim().toLowerCase();
    if (cleanQuery.isEmpty) return true;
    if (cleanTarget.isEmpty) return false;

    // 1. Case-insensitive substring match
    if (cleanTarget.toLowerCase().contains(cleanQuery)) {
      return true;
    }

    // 2. Extract Pinyin initials from target Chinese characters
    final initialsBuffer = StringBuffer();
    for (var i = 0; i < cleanTarget.length; i++) {
      final char = cleanTarget[i];
      final initial = _charPinyinInitial[char];
      if (initial != null) {
        initialsBuffer.write(initial);
      } else {
        // Keep non-Chinese characters (ASCII / numbers / letters)
        initialsBuffer.write(char.toLowerCase());
      }
    }

    final initials = getPinyinInitials(cleanTarget);
    return initials.contains(cleanQuery);
  }

  /// Converts target text to Pinyin initials string.
  static String getPinyinInitials(String target) {
    final cleanTarget = target.trim();
    final initialsBuffer = StringBuffer();
    for (final char in cleanTarget.split('')) {
      final initial = _charPinyinInitial[char];
      if (initial != null) {
        initialsBuffer.write(initial);
      } else {
        initialsBuffer.write(char.toLowerCase());
      }
    }
    return initialsBuffer.toString();
  }
